def main() -> None:
    ROOT.joinpath("data/processed").mkdir(parents=True, exist_ok=True)
    ROOT.joinpath("reports/spelling_challenge").mkdir(parents=True, exist_ok=True)

    records = []
    idx = 1

    for row in EXAMPLES_RAW:
        text, sentiment, cat, vtype, adv, norm_help, notes = row
        records.append(
            {
                "id": f"spch_{idx:03d}",
                "text": text,
                "sentiment": sentiment,
                "variation_category": cat,
                "variation_type": vtype,
                "is_adversarial": adv,
                "normalization_should_help": norm_help,
                "notes": notes,
            }
        )
        idx += 1

    # Minimal pairs
    pair_records = []
    for row in MINIMAL_PAIRS_RAW:
        (
            pid,
            ta,
            tb,
            sa,
            sb,
            cat,
            vtype,
            adv_a,
            adv_b,
            help_a,
            help_b,
            notes_a,
            notes_b,
        ) = row
        pair_records.append(
            {
                "id": f"{pid}a",
                "text": ta,
                "sentiment": sa,
                "variation_category": cat,
                "variation_type": vtype,
                "is_adversarial": adv_a,
                "normalization_should_help": help_a,
                "notes": notes_a,
            }
        )
        pair_records.append(
            {
                "id": f"{pid}b",
                "text": tb,
                "sentiment": sb,
                "variation_category": cat,
                "variation_type": vtype,
                "is_adversarial": adv_b,
                "normalization_should_help": help_b,
                "notes": notes_b,
            }
        )

    all_records = records + pair_records
    total = len(all_records)

    # ── Write spelling_challenge.jsonl ────────────────────────────────────
    out_path = ROOT / "data/processed/spelling_challenge.jsonl"
    with out_path.open("w", encoding="utf-8") as fh:
        for rec in all_records:
            fh.write(json.dumps(rec, ensure_ascii=False) + "\n")
    print(f"Wrote {total} records → {out_path}")

    # ── Compute counts ────────────────────────────────────────────────────
    from collections import Counter

    cat_counts: dict[str, Counter] = {}
    sentiment_counts: Counter = Counter()
    adv_count = 0

    for r in all_records:
        cat = r["variation_category"]
        sent = r["sentiment"]
        if cat not in cat_counts:
            cat_counts[cat] = Counter()
        cat_counts[cat][sent] += 1
        sentiment_counts[sent] += 1
        if r["is_adversarial"]:
            adv_count += 1

    # adversarial per category
    adv_by_cat: Counter = Counter()
    for r in all_records:
        if r["is_adversarial"]:
            adv_by_cat[r["variation_category"]] += 1

    # ── Write manifest ────────────────────────────────────────────────────
    manifest = {
        "version": "1.0",
        "frozen_at": "2026-10-30",
        "total_examples": total,
        "variation_category_counts": {
            cat: dict(ctr) for cat, ctr in cat_counts.items()
        },
        "sentiment_counts": dict(sentiment_counts),
        "adversarial_count": adv_count,
        "minimal_pairs_count": len(MINIMAL_PAIRS_RAW),
        "dedup_check": "no_overlap_with_benchmark",
        "review_note": "Synthetic examples; fluent-speaker review pending",
    }
    manifest_path = ROOT / "data/processed/spelling_challenge_manifest.json"
    with manifest_path.open("w", encoding="utf-8") as fh:
        json.dump(manifest, fh, indent=2, ensure_ascii=False)
    print(f"Wrote manifest → {manifest_path}")

    # ── Write balance_chart.md ────────────────────────────────────────────
    CATS = [
        "vowel_variation",
        "consonant_variation",
        "repeated_chars",
        "omitted_letters",
        "abbreviations",
        "spacing_variation",
    ]
    SENTS = ["positive", "negative", "neutral"]

    lines = [
        "# Spelling Challenge Balance Chart\n",
        "## Distribution by Category and Sentiment\n",
    ]

    # Table header
    header = "| Category           | positive | negative | neutral | Total | Adv |"
    sep = "|--------------------|----------|----------|---------|-------|-----|"
    lines += [header, sep]

    bar_lines = ["\n## ASCII Bar Chart (Total per Category)\n", "```"]
    for cat in CATS:
        ctr = cat_counts.get(cat, Counter())
        pos = ctr.get("positive", 0)
        neg = ctr.get("negative", 0)
        neu = ctr.get("neutral", 0)
        tot = pos + neg + neu
        adv = adv_by_cat.get(cat, 0)
        short = cat[:18].ljust(18)
        lines.append(f"| {short} | {pos:8d} | {neg:8d} | {neu:7d} | {tot:5d} | {adv:3d} |")
        bar = "#" * tot
        bar_lines.append(f"{short} | {bar} ({tot})")

    bar_lines.append("```")

    lines += [
        f"\n**Total examples:** {total}",
        f"**Adversarial total:** {adv_count}",
        f"**Minimal pairs:** {len(MINIMAL_PAIRS_RAW)}",
        "",
        "## Sentiment Totals\n",
        "| Sentiment | Count |",
        "|-----------|-------|",
    ]
    for s in SENTS:
        lines.append(f"| {s:9s} | {sentiment_counts.get(s, 0):5d} |")

    lines += [""] + bar_lines

    lines += [
        "\n## Adversarial vs Realistic per Category\n",
        "| Category           | Realistic | Adversarial |",
        "|--------------------|-----------|-------------|",
    ]
    for cat in CATS:
        ctr = cat_counts.get(cat, Counter())
        tot = sum(ctr.values())
        adv = adv_by_cat.get(cat, 0)
        real = tot - adv
        short = cat[:18].ljust(18)
        lines.append(f"| {short} | {real:9d} | {adv:11d} |")

    chart_path = ROOT / "reports/spelling_challenge/balance_chart.md"
    chart_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote chart → {chart_path}")


if __name__ == "__main__":
    main()
